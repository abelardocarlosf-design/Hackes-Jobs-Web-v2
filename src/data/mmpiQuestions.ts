interface Reactivo { escala: Escala; texto: string; claveVerdadero: boolean }

const TODOS: Reactivo[] = barajar(
  (Object.keys(REACTIVOS) as Escala[]).flatMap(escala =>
    REACTIVOS[escala].map(t => ({ escala, texto: t.slice(1), claveVerdadero: t[0] === '+' }))
  ),
  20261005
);

export const MMPI_QUESTIONS: ChoiceQuestion[] = TODOS.map((r, i) => {
  const id = String(i + 1);
  return {
    id,
    question: r.texto,
    options: [
      { id: `mmpi_${id}_v`, text: 'Verdadero', clave: r.escala, valor: r.claveVerdadero ? 1 : 0 },
      { id: `mmpi_${id}_f`, text: 'Falso', clave: r.escala, valor: r.claveVerdadero ? 0 : 1 },
    ],
  };
});

export function calificarMMPI(answers: Record<string, string>) {
  const escalas = Object.keys(MMPI_ESCALAS) as Escala[];
  const crudo = Object.fromEntries(escalas.map(e => [e, 0])) as Record<Escala, number>;
  const reactivos = { ...crudo };
  let sinRespuesta = 0;
  for (const q of MMPI_QUESTIONS) {
    const e = q.options[0].clave as Escala;
    reactivos[e]++;
    const op = q.options.find(o => o.id === answers[q.id]);
    if (!op) { sinRespuesta++; continue; }
    crudo[e] += op.valor ?? 0;
  }
  return {
    nota: 'Puntaje crudo = respuestas en la dirección clave de cada escala. No son puntuaciones T: el banco es propio y no tiene normas poblacionales, así que la lectura es relativa (porcentaje del máximo de cada escala). Mf se interpreta según el sexo del evaluado. "?" = reactivos sin responder.',
    '?': sinRespuesta,
    por_escala: Object.fromEntries(
      escalas.map(e => [e, { escala: MMPI_ESCALAS[e], crudo: crudo[e], reactivos: reactivos[e], porcentaje: Math.round((crudo[e] / reactivos[e]) * 100) }])
    ),
  };
}

